import assert from 'node:assert/strict';
import { bookingUrl } from '../src/lib/booking-url.ts';
const base = 'https://meetings-eu1.hubspot.com/person/meeting?uuid=keep-me#calendar';
let url = new URL(bookingUrl(base, 'hero'));
assert.equal(url.searchParams.get('uuid'), 'keep-me');
assert.equal(url.hash, '#calendar');
assert.equal(url.searchParams.get('utm_source'), 'promofy_website');
assert.equal(url.searchParams.get('utm_medium'), 'website');
assert.equal(url.searchParams.get('utm_campaign'), 'sbc_lisbon_2026');
assert.equal(url.searchParams.get('utm_content'), 'hero');
url = new URL(bookingUrl(base + '&utm_source=existing', 'team_irakli', '?utm_source=linkedin&utm_medium=social&utm_campaign=launch&utm_term=sports&email=private@example.com'));
assert.equal(url.searchParams.get('utm_source'), 'linkedin');
assert.equal(url.searchParams.get('utm_campaign'), 'launch');
assert.equal(url.searchParams.get('utm_term'), 'sports');
assert.equal(url.searchParams.get('utm_content'), 'team_irakli');
assert.equal(url.searchParams.has('email'), false);
url = new URL(bookingUrl('https://example.com/meeting?utm_source=partner&utm_medium=email', 'final', '?utm_source='));
assert.equal(url.searchParams.get('utm_source'), 'partner');
assert.equal(url.searchParams.get('utm_medium'), 'email');
assert.equal(url.searchParams.getAll('utm_content').length, 1);
console.log('Booking URL checks passed: defaults, incoming campaign tags, placement, existing parameters, and no unrelated query forwarding.');
